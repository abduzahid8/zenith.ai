import {
    Task,
    TaskType,
    TaskStatus,
    UserStateSnapshot,
    UserHobby,
    UserEarning,
    EarningMethod
} from './supabase/types';
import { TASK_BANK } from '../data/taskBank';
import { getAutoTasksPerDay, getMaxTasksPerDay } from '../domain/tasks/rules';

export const taskEngine = {
    generateDailyPlan: (
        userId: string,
        dateString: string,
        snapshot: UserStateSnapshot | null,
        hobbies: UserHobby[],
        activeEarnings: UserEarning[] = [],
        earningMethods: EarningMethod[] = [],
        isPremium: boolean = false
    ): Task[] => {
        const tasks: Task[] = [];

        // Identify primary hobby
        const primaryHobby = hobbies.find(h => h.is_primary) || hobbies[0];
        const hobbyId = primaryHobby?.hobby_id;

        // --- Calculate which day the user is on ---
        const startDate = primaryHobby?.selected_at
            ? new Date(primaryHobby.selected_at)
            : new Date(dateString);
        const today = new Date(dateString);
        const msPerDay = 1000 * 60 * 60 * 24;
        const dayNumber = Math.max(1, Math.floor((today.getTime() - startDate.getTime()) / msPerDay) + 1);
        // Cap at 28 (one month of content), then cycle back
        const dayIndex = ((dayNumber - 1) % 28) + 1;

        // --- Pull tasks from TASK_BANK for this exact day ---
        const hobbyBank = TASK_BANK[hobbyId];
        const dayData = hobbyBank?.find(d => d.day === dayIndex);

        if (dayData) {
            // Generate all 4 task types from the bank
            const taskDefs: { type: TaskType; title: string; duration: number }[] = [
                { type: 'theory',   title: dayData.theory,   duration: 15 },
                { type: 'practice', title: dayData.practice, duration: 30 },
                { type: 'puzzles',  title: dayData.puzzles,  duration: 20 },
                { type: 'analysis', title: dayData.analysis, duration: 20 },
            ];

            taskDefs.forEach(({ type, title, duration }) => {
                tasks.push({
                    user_id: userId,
                    title,
                    type,
                    status: 'pending',
                    hobby_id: hobbyId,
                    scheduled_date: dateString,
                    duration_minutes: duration,
                    is_ai_generated: false,
                });
            });
        } else {
            // Fallback: use random templates if no bank entry found
            const difficultyLevel = 'beginner';
            const pairs: [TaskType, TaskType][] = [
                ['theory', 'puzzles'],
                ['practice', 'analysis'],
                ['theory', 'practice'],
            ];
            const selectedPair = pairs[Math.floor(Math.random() * pairs.length)];
            selectedPair.forEach(type => {
                let title = '';
                let duration = 15;
                switch (type) {
                    case 'theory':   title = generateTheoryTitle(hobbyId, difficultyLevel);   duration = 15; break;
                    case 'practice': title = generatePracticeTitle(hobbyId, difficultyLevel); duration = 30; break;
                    case 'analysis': title = generateAnalysisTitle(hobbyId);                  duration = 20; break;
                    case 'puzzles':  title = generatePuzzlesTitle(hobbyId);                   duration = 20; break;
                }
                tasks.push({
                    user_id: userId,
                    title,
                    type,
                    status: 'pending',
                    hobby_id: hobbyId,
                    scheduled_date: dateString,
                    duration_minutes: duration,
                    is_ai_generated: false,
                });
            });
        }

        return tasks.slice(0, getAutoTasksPerDay());
    },

    generateTaskByType: (
        userId: string,
        type: TaskType,
        dateString: string,
        snapshot: UserStateSnapshot | null,
        hobbies: UserHobby[],
        template?: { title: string; duration: number } // Added optional template
    ): Task => {
        // Default params
        let baseDuration = 15;
        let difficultyLevel = 'beginner';

        if (snapshot) {
            if (snapshot.avg_session_time && snapshot.avg_session_time > 0) {
                baseDuration = Math.min(60, Math.max(5, snapshot.avg_session_time + 5));
            }
        }

        const primaryHobby = hobbies.find(h => h.is_primary) || hobbies[0];
        const hobbyId = primaryHobby?.hobby_id;

        let title = '';
        let duration = baseDuration;

        if (template) {
            title = template.title;
            duration = template.duration;
        } else {
            // Fallback to random generation if no template provided
            switch (type) {
                case 'theory':
                    title = generateTheoryTitle(hobbyId, difficultyLevel);
                    duration = 15;
                    break;
                case 'practice':
                    title = generatePracticeTitle(hobbyId, difficultyLevel);
                    duration = 30;
                    break;
                case 'analysis':
                    title = generateAnalysisTitle(hobbyId);
                    duration = 20;
                    break;
                case 'puzzles':
                    title = generatePuzzlesTitle(hobbyId);
                    duration = 15;
                    break;
                default:
                    title = 'New Task';
                    duration = 15;
            }
        }

        return {
            user_id: userId,
            title,
            type,
            status: 'pending',
            hobby_id: hobbyId,
            scheduled_date: dateString,
            duration_minutes: duration,
            is_ai_generated: false,
            is_manual: true // Mark as manually added
        };
    },

    getAvailableTaskTemplates: (hobbyId: string | undefined, type: TaskType): TaskTemplate[] => {
        const hobbyKey = hobbyId && TASK_TEMPLATES_DATA[hobbyId] ? hobbyId : 'default';
        return TASK_TEMPLATES_DATA[hobbyKey]?.[type] || TASK_TEMPLATES_DATA['default'][type] || [];
    },
};

